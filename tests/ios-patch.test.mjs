test('deployment target moves to 15.0 (StoreKit 2) in the project and the Podfile, idempotently', () => {
  const pbx = 'IPHONEOS_DEPLOYMENT_TARGET = 14.0;\nx\nIPHONEOS_DEPLOYMENT_TARGET = 14.0;', pod = "platform :ios, '14.0'\nuse_frameworks!";
  const a = patchDeploymentTarget(pbx, pod);
  assert.equal(a.projectCount, 2); assert.equal(a.podfileCount, 1); assert.ok(!/14\.0/.test(a.pbx + a.podfile));
  const b = patchDeploymentTarget(a.pbx, a.podfile); assert.equal(b.pbx, a.pbx); assert.equal(b.podfile, a.podfile);
});

test('scheme: Run uses the StoreKit file, Archive does not; target id is read from the real project', () => {
  const id = appTargetId(fs.readFileSync(path.join(ROOT, 'ios/App/App.xcodeproj/project.pbxproj'), 'utf8'));
  assert.match(id, /^[0-9A-F]{24}$/);
  const x = schemeXml(id);
  assert.equal(x.split(id).length - 1, 3); assert.match(/<LaunchAction[\s\S]*<\/LaunchAction>/.exec(x)[0], /GraveGoods\.storekit/); assert.ok(!/StoreKit/.test(/<ArchiveAction[\s\S]*<\/ArchiveAction>/.exec(x)[0]));
  assert.throws(() => appTargetId('nothing here'), /not found/);
});
