const TEMPLATE_PLIST = `<?xml version="1.0" encoding="UTF-8"?>
<plist version="1.0">
<dict>
	<key>CFBundleName</key>
	<string>$(PRODUCT_NAME)</string>
	<key>UIRequiredDeviceCapabilities</key>
	<array>
		<string>armv7</string>
	</array>
</dict>
</plist>
`;
const TEMPLATE_PBX = `
			buildSettings = {
				CODE_SIGN_STYLE = Automatic;
				PRODUCT_BUNDLE_IDENTIFIER = com.old.id;
			};
			buildSettings = {
				CODE_SIGN_STYLE = Automatic;
				PRODUCT_BUNDLE_IDENTIFIER = com.old.id;
			};`;

test('Info.plist patch adds ATT/AdMob/encryption keys, fixes arm64, and is idempotent', () => {
  const a = patchInfoPlist(TEMPLATE_PLIST);
  for (const k of ['ITSAppUsesNonExemptEncryption', 'NSUserTrackingUsageDescription', 'GADApplicationIdentifier', 'SKAdNetworkItems']) assert.ok(a.plist.includes(`<key>${k}</key>`), k);
  assert.ok(a.plist.includes('<string>arm64</string>') && !a.plist.includes('armv7'));
  assert.ok(a.plist.includes(GOOGLE_TEST_APP_ID));
  assert.equal(patchInfoPlist(a.plist).changed, 0, 'second run changes nothing');
  const b = patchInfoPlist(a.plist, { admobAppId: 'ca-app-pub-1~2' }); assert.equal(b.changed, 1); assert.ok(b.plist.includes('ca-app-pub-1~2') && !b.plist.includes(GOOGLE_TEST_APP_ID));
  assert.deepEqual(plistEnsure(a.plist, 'ITSAppUsesNonExemptEncryption', '<true/>')[1], false);
});

test('project.pbxproj: bundle id and entitlements set in both configurations, idempotent', () => {
  const a = patchPbxproj(TEMPLATE_PBX, 'com.example.gg');
  assert.equal(a.bundleCount, 2); assert.equal((a.pbx.match(/CODE_SIGN_ENTITLEMENTS = App\/App\.entitlements;/g) || []).length, 2);
  assert.equal((a.pbx.match(/com\.example\.gg/g) || []).length, 2); assert.ok(!a.pbx.includes('com.old.id'));
  const b = patchPbxproj(a.pbx, 'com.example.gg'); assert.equal(b.pbx, a.pbx);
});

test('patchIos on a copy of the real project: runs twice, leaves a valid result', () => {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'gg-ios-'));
  fs.cpSync(path.join(ROOT, 'ios/App'), path.join(tmp, 'ios/App'), { recursive: true, filter: s => !/Pods|build/.test(s) });
  fs.copyFileSync(path.join(ROOT, 'capacitor.config.ts'), path.join(tmp, 'capacitor.config.ts'));
  fs.cpSync(path.join(ROOT, 'assets'), path.join(tmp, 'assets'), { recursive: true });
  assert.throws(() => patchIos({ root: tmp, env: { BUNDLE_ID: 'com.test.bundle' }, log: () => {} }), /must match/);
  fs.writeFileSync(path.join(tmp, 'capacitor.config.ts'), fs.readFileSync(path.join(tmp, 'capacitor.config.ts'), 'utf8').replace('com.gravegoods.app', 'com.test.bundle'));
  patchIos({ root: tmp, env: { BUNDLE_ID: 'com.test.bundle', ADMOB_APP_ID_IOS: 'ca-app-pub-9~9' }, log: () => {} });
  const first = fs.readFileSync(path.join(tmp, 'ios/App/App.xcodeproj/project.pbxproj'), 'utf8');
  patchIos({ root: tmp, env: { BUNDLE_ID: 'com.test.bundle', ADMOB_APP_ID_IOS: 'ca-app-pub-9~9' }, log: () => {} });
  assert.equal(fs.readFileSync(path.join(tmp, 'ios/App/App.xcodeproj/project.pbxproj'), 'utf8'), first);
  assert.match(first, /PRODUCT_BUNDLE_IDENTIFIER = com\.test\.bundle;/);
  const ent = fs.readFileSync(path.join(tmp, 'ios/App/App/App.entitlements'), 'utf8');
  assert.match(ent, /com\.apple\.developer\.ubiquity-kvstore-identifier/);
  const icon = fs.readFileSync(path.join(tmp, 'ios/App/App/Assets.xcassets/AppIcon.appiconset/AppIcon-512@2x.png'));
  assert.equal(colorType(icon), 2, 'icon has no alpha channel'); assert.deepEqual([icon.readUInt32BE(16), icon.readUInt32BE(20)], [1024, 1024]);
});

