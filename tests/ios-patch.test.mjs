test('PNG flatten: RGBA with transparent pixels becomes opaque RGB over the background colour', () => {
  const w = 4, h = 2, stride = w * 4 + 1, raw = Buffer.alloc(stride * h);
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) { const o = y * stride + 1 + x * 4; raw.set(x < 2 ? [255, 0, 0, 255] : [0, 255, 0, 0], o); }
  const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(w, 0); ihdr.writeUInt32BE(h, 4); ihdr[8] = 8; ihdr[9] = 6;
  const crc = b => { let c = ~0; for (const x of b) { c ^= x; for (let k = 0; k < 8; k++) c = c & 1 ? (c >>> 1) ^ 0xedb88320 : c >>> 1; } return ~c >>> 0; };
  const ch = (t, d) => { const l = Buffer.alloc(4); l.writeUInt32BE(d.length); const td = Buffer.concat([Buffer.from(t), d]); const c = Buffer.alloc(4); c.writeUInt32BE(crc(td)); return Buffer.concat([l, td, c]); };
  const png = Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), ch('IHDR', ihdr), ch('IDAT', zlib.deflateSync(raw)), ch('IEND', Buffer.alloc(0))]);
  assert.equal(colorType(png), 6);
  const out = flattenToRGB(png, [10, 20, 30]), im = decode(out);
  assert.equal(im.ct, 2); assert.deepEqual([...im.pixels.subarray(0, 3)], [255, 0, 0]); assert.deepEqual([...im.pixels.subarray(6, 9)], [10, 20, 30]);
  assert.equal(decode(solidPng(8, 8, [1, 2, 3])).pixels[0], 1);
});

